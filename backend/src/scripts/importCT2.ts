function main(): void {
  const db = getDb()

  const existing = db.prepare(`SELECT id FROM floors WHERE code = ?`).get(floorRow.code) as { id: number } | undefined
  if (existing) {
    console.log(`[import:ct2] 楼层 ${floorRow.code} 已存在（id=${existing.id}），整批跳过。如需重录请先在编辑器中删除该楼层。`)
    closeDb()
    return
  }

  const tx = db.transaction(() => {
    const f = floorRow
    const info = db
      .prepare(
        `INSERT INTO floors (name, latinName, code, designation, theme, receptionType, battleSystem, description, sortOrder, artwork)
         VALUES (@name, @latinName, @code, @designation, @theme, @receptionType, @battleSystem, @description, @sortOrder, @artwork)`,
      )
      .run(f)
    const floorId = Number(info.lastInsertRowid)
    console.log(`[import:ct2] 楼层 ${f.code} ${f.name} -> id=${floorId}`)

    const insLib = db.prepare(
      `INSERT INTO librarians (name, title, department, role, floorId, rarity, coreColor, affiliation, status, description, sheet, portrait, portraitPreview, sortOrder)
       VALUES (@name, @title, 'turris', 'curator', @floorId, @rarity, '', @affiliation, '在任', '', @sheet, '', '', @sortOrder)`,
    )
    librarianRows.forEach((row, i) => {
      insLib.run({ ...row, floorId, sortOrder: i + 1 })
    })
    console.log(`[import:ct2] 司书 ${librarianRows.length} 条（含附加单位）`)

    const insEmotion = db.prepare(
      `INSERT INTO emotion_entities (floorId, code, name, sheet, sortOrder) VALUES (@floorId, @code, @name, @sheet, @sortOrder)`,
    )
    emotionRows.forEach((row, i) => {
      insEmotion.run({ ...row, floorId, sortOrder: i })
    })
    console.log(`[import:ct2] 情感书页实体 ${emotionRows.length} 条`)
  })

  tx()
  closeDb()
  console.log('[import:ct2] 完成。')
}

main()
