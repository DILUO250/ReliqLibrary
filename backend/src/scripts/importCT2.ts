/* ============================ 通用助手 ============================ */

type Die = { baseType: string; specialType: string; rangeMin: number; rangeMax: number; effects: string[] }
type Card = { name: string; cost: number; type: string; tags: string[]; effects: string[]; dice: Die[]; egoPassive?: { name: string; effect: string } }
type Page = { name: string; cost: string; effect: string; mechanisms: Mechanism[] }
type Ego = Card

/** 骰子：baseType（斩击/突刺/打击/招架/闪避），min-max，命中效果；反击骰用 specialType='反击'。 */
const d = (baseType: string, rangeMin: number, rangeMax: number, effects: string[] = [], specialType = ''): Die =>
  ({ baseType, specialType, rangeMin, rangeMax, effects })

/** 卡牌。tags 不含方括号，如 '清算'、'攻击容量:4'。 */
const c = (name: string, cost: number, type: string, tags: string[], effects: string[] = [], dice: Die[] = []): Card =>
  ({ name, cost, type, tags, effects, dice })

/** EGO 卡牌（情感书页用，带 EGO 被动）。 */
const ego = (name: string, cost: number, type: string, tags: string[], effects: string[], dice: Die[], passive: { name: string; effect: string }): Ego =>
  ({ name, cost, type, tags, effects, dice, egoPassive: passive })

/** 特殊机制。type 形如 能力/正面状态/负面状态/中立状态/标记/负面情感。 */
const m = (name: string, type: string, desc: string, stack = ''): Mechanism =>
  ({ name, stack, type, desc })

const p = (name: string, effect: string): Passive => ({ name, effect })

/** 抗性简写：n=一般(1) t=耐性(0.5) w=脆弱(1.5) f=致命(2) r=抵抗(0)，按 斩/突/打 顺序。 */
const RV: Record<string, number> = { n: 1, t: 0.5, w: 1.5, f: 2, r: 0 }
const res = (phys: string, chaos: string) => {
  const parse = (s: string) => {
    const [a, b, cc] = s.trim().split(/\s+/)
    return { slash: RV[a!] ?? 1, pierce: RV[b!] ?? 1, strike: RV[cc!] ?? 1 }
  }
  return { physic: parse(phys), chaos: parse(chaos) }
}

/** 司书 sheet。文档未给的数值（体/速）按 0 占位待人工校订（与 CT-1 附加单位惯例一致）。 */
function libSheet(name: string, o: {
  hp?: number
  stagger?: number
  speed?: [number, number]
  phys: string
  chaos: string
  passives: Passive[]
  mechs?: Mechanism[]
  combat: Card[]
  special?: Card[]
  ego?: Card[]
  sys?: Record<string, unknown>
}): string {
  const sys = { hasSanity: false, hasEgo: false, hasMind: false, ...(o.sys ?? {}) }
  return JSON.stringify({
    battleSystem: 'lob',
    romanNum: '',
    name,
    hp: o.hp ?? 0,
    stagger: o.stagger ?? 0,
    sanity: 0,
    speedMin: o.speed?.[0] ?? 0,
    speedMax: o.speed?.[1] ?? 0,
    resist: res(o.phys, o.chaos),
    factions: [],
    faction: '',
    passives: o.passives,
    mechanisms: o.mechs ?? [],
    cards: { combat: o.combat, special: o.special ?? [], ego: o.ego ?? [] },
    systemData: sys,
  })
}

/** 情感书页 sheet。 */
const emSheet = (pages: Page[], egoCards: Ego[]): string => JSON.stringify({ pages, egoCards })

